import type { Metadata } from "next";
import Link from "next/link";
import { CircleCheck, FlaskConical, Hourglass, Landmark, Wallet } from "lucide-react";
import { DataTable, Td, Th, Tr } from "@/components/common/data-table";
import { PageHeader } from "@/components/common/page-header";
import { EmptyState, Section } from "@/components/common/panels";
import { StatCard, StatGrid } from "@/components/common/stat-card";
import { DemoBadge, StatusBadge } from "@/components/common/status-badge";
import { Button } from "@/components/ui/button";
import { formatDateTime } from "@/lib/format";
import { formatINR, formatINRCompact, sumPaise } from "@/lib/money";
import { requireWorkspace } from "@/server/auth/session";
import { listPartnerDisbursements } from "@/server/queries/partner";

export const metadata: Metadata = { title: "Disbursements" };

export default async function DisbursementsPage() {
  const actor = await requireWorkspace("partner");
  const { disbursements, awaiting } = await listPartnerDisbursements(actor);
  const paid = disbursements.filter((d) => d.status === "SUCCESS");
  const processing = disbursements.filter((d) => d.status === "INITIATED");

  return (
    <>
      <PageHeader
        eyebrow="Early payment"
        title="Disbursements"
        description="Payouts of the net discounted amount to your registered bank account."
        actions={<DemoBadge />}
      />

      <div role="note" className="mb-6 flex animate-fade-up items-start gap-3 rounded-lg border border-gold/30 bg-gold-100/60 px-5 py-4 text-sm text-slate-ink">
        <FlaskConical className="mt-0.5 size-4 shrink-0 text-gold-600" />
        <p>
          <span className="font-semibold text-navy">Simulated payments.</span> No bank integration is connected in this demonstration. Payment references and UTR numbers are
          generated by BrickFlow to illustrate the flow; no real funds move.
        </p>
      </div>

      <StatGrid className="mb-8 xl:grid-cols-4 2xl:grid-cols-4">
        <StatCard label="Total received (simulated)" value={formatINRCompact(sumPaise(paid.map((d) => d.amountPaise)))} hint={`${paid.length} completed payouts`} icon={Wallet} tone="heritage" />
        <StatCard label="In process" value={formatINRCompact(sumPaise(processing.map((d) => d.amountPaise)))} hint={`${processing.length} initiated, awaiting confirmation`} icon={Hourglass} tone="gold" />
        <StatCard
          label="Approved, awaiting payout"
          value={formatINRCompact(sumPaise(awaiting.map((r) => r.netPayablePaise)))}
          hint={`${awaiting.length} ${awaiting.length === 1 ? "request" : "requests"} approved by Veefin`}
          icon={CircleCheck}
        />
        <StatCard label="Payout instructions" value={disbursements.length} hint="All simulated transfers" icon={Landmark} tone="slate" />
      </StatGrid>

      <div className="flex flex-col gap-6">
        <Section title="Payout history" description="Most recent first" bodyClassName="py-0">
          {disbursements.length === 0 ? (
            <EmptyState
              icon={Wallet}
              title="No disbursements yet"
              description="When Veefin pays out an approved financing request, the simulated transfer appears here."
              action={
                <Button variant="outline" size="sm" asChild>
                  <Link href="/partner/transactions">View my transactions</Link>
                </Button>
              }
            />
          ) : (
            <DataTable minWidth={1120}>
              <thead>
                <tr>
                  <Th>Payment reference</Th>
                  <Th>Invoice</Th>
                  <Th align="right">Net amount</Th>
                  <Th>Status</Th>
                  <Th>UTR (simulated)</Th>
                  <Th>Initiated</Th>
                  <Th>Completed</Th>
                  <Th>Beneficiary account</Th>
                </tr>
              </thead>
              <tbody>
                {disbursements.map((d) => (
                  <Tr key={d.id}>
                    <Td>
                      <p className="font-medium text-navy">{d.reference}</p>
                      <p className="text-xs text-muted-foreground">{d.request.reference}</p>
                    </Td>
                    <Td>
                      <Link href={`/partner/invoices/${d.request.invoice.id}`} className="text-navy hover:underline">
                        {d.request.invoice.invoiceNumber}
                      </Link>
                      <p className="text-xs text-muted-foreground">{d.request.invoice.builder.name}</p>
                    </Td>
                    <Td align="right" className="font-semibold text-heritage">
                      {formatINR(d.amountPaise)}
                    </Td>
                    <Td>
                      <StatusBadge kind="disbursement" status={d.status} />
                    </Td>
                    <Td className="font-mono text-xs">{d.utr ?? "Pending"}</Td>
                    <Td className="whitespace-nowrap">{formatDateTime(d.initiatedAt)}</Td>
                    <Td className="whitespace-nowrap">{formatDateTime(d.completedAt)}</Td>
                    <Td>
                      <p className="font-mono text-xs">{d.beneficiaryAccount}</p>
                      <p className="text-xs text-muted-foreground">
                        {d.beneficiaryIfsc} · {d.mode === "DEMO_SIMULATED" ? "Simulated" : d.mode}
                      </p>
                    </Td>
                  </Tr>
                ))}
              </tbody>
            </DataTable>
          )}
        </Section>

        {awaiting.length > 0 && (
          <Section title="Approved, awaiting payout" description="Veefin has approved these requests; the simulated transfer has not started yet" bodyClassName="py-0">
            <DataTable minWidth={720}>
              <thead>
                <tr>
                  <Th>Request</Th>
                  <Th>Invoice</Th>
                  <Th align="right">Net payable</Th>
                  <Th>Approved on</Th>
                  <Th>Status</Th>
                </tr>
              </thead>
              <tbody>
                {awaiting.map((r) => (
                  <Tr key={r.id}>
                    <Td className="font-medium text-navy">{r.reference}</Td>
                    <Td>
                      <Link href={`/partner/invoices/${r.invoice.id}`} className="text-navy hover:underline">
                        {r.invoice.invoiceNumber}
                      </Link>
                      <p className="text-xs text-muted-foreground">{r.builder.name}</p>
                    </Td>
                    <Td align="right" className="font-semibold text-heritage">
                      {formatINR(r.netPayablePaise)}
                    </Td>
                    <Td className="whitespace-nowrap">{formatDateTime(r.decidedAt)}</Td>
                    <Td>
                      <StatusBadge kind="financing" status={r.status} />
                    </Td>
                  </Tr>
                ))}
              </tbody>
            </DataTable>
          </Section>
        )}
      </div>
    </>
  );
}
