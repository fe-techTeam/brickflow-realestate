import type { Metadata } from "next";
import Link from "next/link";
import { FlaskConical, Wallet } from "lucide-react";
import { Button } from "@/components/ui/button";
import { formatDateTime } from "@/lib/format";
import { sumPaise } from "@/lib/money";
import { requireWorkspace } from "@/server/auth/session";
import { listPartnerDisbursements } from "@/server/queries/partner";
import { CompactMoney, Money } from "../_components/money";
import { RefCell, Table, Td, Th, Tr } from "../_components/table";
import { EmptyNote, MetricStrip, PageIntro, Panel, SimulatedTag, StatusMark } from "../_components/ui";

export const metadata: Metadata = { title: "Disbursements" };

export default async function DisbursementsPage() {
  const actor = await requireWorkspace("partner");
  const { disbursements, awaiting } = await listPartnerDisbursements(actor);
  const paid = disbursements.filter((d) => d.status === "SUCCESS");
  const processing = disbursements.filter((d) => d.status === "INITIATED");

  return (
    <>
      <PageIntro
        eyebrow="Early payment"
        title="Disbursements"
        description="Payouts of the net discounted amount to your registered bank account."
        actions={<SimulatedTag label="Simulated payments" />}
      />

      <MetricStrip
        className="mb-6"
        items={[
          { label: "Total received", value: <CompactMoney paise={sumPaise(paid.map((d) => d.amountPaise))} size="xl" />, hint: `${paid.length} completed ${paid.length === 1 ? "payout" : "payouts"}`, accent: "leaf" },
          {
            label: "In process",
            value: <CompactMoney paise={sumPaise(processing.map((d) => d.amountPaise))} size="xl" />,
            hint: `${processing.length} initiated, awaiting confirmation`,
            accent: "kota",
          },
          {
            label: "Approved, awaiting payout",
            value: <CompactMoney paise={sumPaise(awaiting.map((r) => r.netPayablePaise))} size="xl" />,
            hint: `${awaiting.length} ${awaiting.length === 1 ? "request" : "requests"} approved by Veefin`,
          },
          { label: "Payout instructions", value: <span className="text-[1.875rem] leading-none font-normal tabular">{disbursements.length}</span>, hint: "All simulated transfers", accent: "slate" },
        ]}
      />

      <div role="note" className="mb-8 flex animate-fade-up items-start gap-3 rounded-xl border border-dashed border-line-strong/45 px-5 py-4 text-[0.8125rem] leading-relaxed text-fg-soft">
        <FlaskConical className="mt-0.5 size-4 shrink-0 text-fg-muted" />
        <p>
          <span className="font-semibold text-fg">Simulated payments.</span> No bank integration is connected in this demonstration. Payment references and UTR numbers are
          generated by BrickFlow to illustrate the flow; no real funds move.
        </p>
      </div>

      <div className="flex flex-col gap-6">
        <Panel eyebrow="Most recent first" title="Payout history" bodyClassName="pb-0">
          {disbursements.length === 0 ? (
            <div className="-mx-5 border-t border-hairline sm:-mx-7">
              <EmptyNote
                icon={Wallet}
                title="No disbursements yet"
                description="When Veefin pays out an approved financing request, the simulated transfer appears here."
                action={
                  <Button variant="outline" size="sm" asChild>
                    <Link href="/partner/transactions">View my transactions</Link>
                  </Button>
                }
              />
            </div>
          ) : (
            <Table minWidth={960}>
              <thead>
                <tr>
                  <Th>Payment reference</Th>
                  <Th>Invoice</Th>
                  <Th align="right">Net amount</Th>
                  <Th>Status · UTR (simulated)</Th>
                  <Th>Initiated · Completed</Th>
                  <Th>Beneficiary</Th>
                </tr>
              </thead>
              <tbody>
                {disbursements.map((d) => (
                  <Tr key={d.id}>
                    <Td>
                      <RefCell primary={d.reference} secondary={d.request.reference} code />
                    </Td>
                    <Td>
                      <RefCell href={`/partner/invoices/${d.request.invoice.id}`} primary={d.request.invoice.invoiceNumber} secondary={d.request.invoice.builder.name} />
                    </Td>
                    <Td align="right">
                      <Money paise={d.amountPaise} className="font-semibold text-leaf" />
                    </Td>
                    <Td>
                      <StatusMark kind="disbursement" status={d.status} />
                      <p className="mt-1 text-xs tracking-wide whitespace-nowrap text-muted-foreground tabular">{d.utr ?? "UTR pending"}</p>
                    </Td>
                    <Td className="text-[0.8125rem] whitespace-nowrap">
                      <p>{formatDateTime(d.initiatedAt)}</p>
                      <p className="mt-0.5 text-xs text-muted-foreground">{d.completedAt ? formatDateTime(d.completedAt) : "Awaiting confirmation"}</p>
                    </Td>
                    <Td>
                      <p className="text-[0.8125rem] tracking-wide text-fg">{d.beneficiaryAccount}</p>
                      <p className="mt-0.5 text-xs whitespace-nowrap text-muted-foreground">
                        {d.beneficiaryIfsc} · {d.mode === "DEMO_SIMULATED" ? "Simulated" : d.mode}
                      </p>
                    </Td>
                  </Tr>
                ))}
              </tbody>
            </Table>
          )}
        </Panel>

        {awaiting.length > 0 && (
          <Panel eyebrow="Queued" title="Approved, awaiting payout" description="Veefin has approved these requests; the simulated transfer has not started yet" bodyClassName="pb-0">
            <Table minWidth={720}>
              <thead>
                <tr>
                  <Th>Request</Th>
                  <Th>Invoice</Th>
                  <Th align="right">Net payable</Th>
                  <Th>Approved on</Th>
                  <Th>Status</Th>
                </tr>
              </thead>
              <tbody>
                {awaiting.map((r) => (
                  <Tr key={r.id}>
                    <Td>
                      <RefCell primary={r.reference} />
                    </Td>
                    <Td>
                      <RefCell href={`/partner/invoices/${r.invoice.id}`} primary={r.invoice.invoiceNumber} secondary={r.builder.name} />
                    </Td>
                    <Td align="right">
                      <Money paise={r.netPayablePaise} className="font-semibold text-leaf" />
                    </Td>
                    <Td className="text-[0.8125rem] whitespace-nowrap">{formatDateTime(r.decidedAt)}</Td>
                    <Td>
                      <StatusMark kind="financing" status={r.status} />
                    </Td>
                  </Tr>
                ))}
              </tbody>
            </Table>
          </Panel>
        )}
      </div>
    </>
  );
}
